import { describe, it, expect } from 'vitest'
import { encode_stl, type STLTriangle } from './encode_stl.js'
import { Vec3 } from '../core/Vec3.js'

const ONE_TRIANGLE: STLTriangle = {
  normal: new Vec3(0, 0, 1),
  a: new Vec3(0, 0, 0),
  b: new Vec3(1, 0, 0),
  c: new Vec3(0, 1, 0)
}

// expected STL file, made with HexEd.it
const STL_ONE_TRIANGLE = new Uint8Array([
  // ASCII[80]: Never gonna give you up / Never gonna let you down
  // followed by a number of zeros
  0x4e, 0x65, 0x76, 0x65, 0x72, 0x20, 0x67, 0x6f, 0x6e, 0x6e, 0x61, 0x20, 0x67, 0x69, 0x76, 0x65,
  0x20, 0x79, 0x6f, 0x75, 0x20, 0x75, 0x70, 0x20, 0x2f, 0x20, 0x4e, 0x65, 0x76, 0x65, 0x72, 0x20,
  0x67, 0x6f, 0x6e, 0x6e, 0x61, 0x20, 0x6c, 0x65, 0x74, 0x20, 0x79, 0x6f, 0x75, 0x20, 0x64, 0x6f,
  0x77, 0x6e, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  // u32: number of triangles = 1
  0x01, 0x00, 0x00, 0x00,
  // normal: (0, 0, 1)
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x3f,
  // v1 = (0, 0, 0)
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  // v2 = (1, 0, 0)
  0x00, 0x00, 0x80, 0x3f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  // v3 = (0, 1, 0)
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x3f, 0x00, 0x00, 0x00, 0x00,
  // 0 additional attributes
  0x00, 0x00
])

describe('encode_stl', () => {
  it('encodes triangle correctly', () => {
    const result = new Uint8Array(encode_stl([ONE_TRIANGLE]))

    const expected = STL_ONE_TRIANGLE
    expect(result).toEqual(expected)
  })
})
